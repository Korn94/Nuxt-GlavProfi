/**
 * 🗂 Соответствие «страница типа помещения → категория портфолио».
 *
 * Зачем отдельный файл:
 * - все 11 страниц `/remont-pomescheniy/*` собираются по одному каркасу
 *   (`pageTypes/<slug>/index.vue`) и блок «Наши реализованные проекты» должен
 *   показывать 2–3 РЕЛЕВАНТНЫХ кейса, а не один «свой» либо пустоту;
 * - фильтрация уходит на сервер (`/api/portfolio?categories=…`), поэтому
 *   странице достаточно знать список категорий, а не конкретные slug'и кейсов;
 * - смежные категории описаны отдельно и только там, где требования к отделке
 *   действительно близки: банк ↔ клиника ↔ офис, салон ↔ клиника,
 *   магазин ↔ кафе ↔ салон. Производственные помещения, фасады и МОПы ни с чем
 *   не смешиваем — кейс кафе на странице ангара выглядит неуместно.
 *
 * ⚠️ Если по категории (и смежным) кейсов нет — секции «Проекты» и
 * «Фото до/после» на странице не рендерятся вовсе (см. `usePortfolioProjects`).
 * Пустых блоков-пустышек быть не должно.
 *
 * Источник значений категорий — enum `portfolioCases.category`
 * в `server/db/schema.ts` (таблица `portfolio_cases`).
 */
import type { PremisesSlug } from './workTypesByCategory'

/** Категория портфолио (совпадает со значениями enum в БД) */
export type PortfolioCategory =
  | 'Кафе'
  | 'Магазины'
  | 'Клиники'
  | 'Банки'
  | 'Фитнес'
  | 'Салоны'
  | 'Офисы'
  | 'Производственные'
  | 'Фасады и Кровля'
  | 'Прочее'

/**
 * Основная категория портфолио для страницы типа помещения.
 * `null` — если подходящей категории нет (блок на странице не показывается).
 */
export const PROJECTS_CATEGORY_BY_PREMISES: Record<PremisesSlug, PortfolioCategory | null> = {
  banki: 'Банки',
  magaziny: 'Магазины',
  ofisy: 'Офисы',
  salony: 'Салоны',
  fitness: 'Фитнес',
  kliniki: 'Клиники',
  proizvodstvo: 'Производственные',
  // Склад, цех и ангар в портфолио лежат в одной категории «Производственные»
  sklady: 'Производственные',
  angary: 'Производственные',
  fasady: 'Фасады и Кровля',
  mopy: 'Прочее',
}

/**
 * Смежные категории — добираем карточки до 2–3, когда в основной категории
 * кейсов мало. Только реально близкие типы объектов.
 * Пустой массив — смежных нет: если в основной категории пусто, блока не будет.
 */
export const PROJECTS_RELATED_CATEGORIES: Record<PremisesSlug, PortfolioCategory[]> = {
  // Режимные объекты: пожарная безопасность, слаботочка, отделка «под стандарт»
  banki: ['Клиники', 'Офисы'],
  ofisy: ['Банки', 'Клиники'],
  // Клиники: кабинеты, мокрые зоны, гигиеничные покрытия
  kliniki: ['Салоны', 'Банки', 'Офисы'],
  // Салоны: клиентские зоны, мокрые зоны, кабинеты
  salony: ['Магазины', 'Клиники'],
  // Магазины: торговые залы в ТЦ, витрины, кафе при магазине
  magaziny: ['Кафе', 'Салоны'],
  // Фитнес: раздевалки, душевые, вентиляция — как в салонах и клиниках
  fitness: ['Салоны', 'Клиники'],
  // Производственные, фасады и МОПы — смежных категорий нет
  proizvodstvo: [],
  sklady: [],
  angary: [],
  fasady: [],
  mopy: [],
}

/** Сколько карточек показываем в блоке «Наши реализованные проекты» */
export const PROJECTS_LIMIT = 3

/**
 * Приоритетный список категорий для запроса к API:
 * [основная, ...смежные]. Порядок важен — по нему сортируются карточки,
 * чтобы «свои» объекты всегда стояли первыми.
 */
export function getProjectsCategories(slug: PremisesSlug): PortfolioCategory[] {
  const main = PROJECTS_CATEGORY_BY_PREMISES[slug]
  if (!main) return []

  const related = PROJECTS_RELATED_CATEGORIES[slug] ?? []
  return [main, ...related.filter((category) => category !== main)]
}

/**
 * Подзаголовок блока «Наши реализованные проекты».
 *
 * Честно проговариваем, что часть карточек — из смежных категорий:
 * заголовок страницы обещает конкретный тип помещения, и подменять его молча нельзя.
 *
 * @param slug       slug страницы типа помещения
 * @param ownCount   сколько карточек относится к основной категории
 * @param totalCount сколько карточек показано всего (по умолчанию — только свои)
 */
export function getProjectsSubtitle(
  slug: PremisesSlug,
  ownCount: number,
  totalCount: number = ownCount,
): string {
  const main = PROJECTS_CATEGORY_BY_PREMISES[slug]
  if (!main) return 'Похожие объекты из портфолио.'

  // Все карточки — из нужной категории: лишних оговорок не нужно
  if (ownCount >= totalCount && ownCount > 0) {
    return 'Реальные объекты в Рязани: площади, сроки и состав работ — без рендеров и обещаний.'
  }

  // Часть карточек — из смежных категорий: проговариваем это прямо
  if (ownCount > 0) {
    return 'Реальные объекты в Рязани. Также показываем проекты из смежных категорий — с похожими требованиями к отделке.'
  }

  return 'Похожие объекты из портфолио: кейсов этой категории пока нет — показываем проекты со схожими требованиями к отделке.'
}
